$script:P2Names = @()

# The P2 clause of section 11.4, reduced to bare identifiers.
#
# The clause is prose a person reads, so the reduction is spelled out and it is
# STRICT: `add<T>` -> add, `Window::openPopup` -> openPopup.  A backticked token
# on that line that does not reduce to an identifier is exit 3, not a skip.  A
# skip would mean a typo in the document silently drops a primitive, and a
# dropped primitive is a silently deleted class of candidate -- the failure this
# whole parse exists to prevent.  Keep prose references out of backticks on that
# one line.
function Read-DoorPrimitivesP2 {
    param([string] $DocPath)

    $result = @{ Names = @(); Error = '' }

    if (-not (Test-Path -LiteralPath $DocPath)) {
        $result.Error = 'design document not found: ' + $DocPath
        return $result
    }

    $lines = [System.IO.File]::ReadAllLines($DocPath, [System.Text.Encoding]::UTF8)
    $inSection = $false
    $clause = $null
    foreach ($line in $lines) {
        if ($line -match '^###\s+11\.4(\s|$)')  { $inSection = $true;  continue }
        if ($inSection -and $line -match '^###\s+11\.5(\s|$)') { break }
        if (-not $inSection) { continue }
        if ($line -match '\*\*P2\*\*') { $clause = $line; break }
    }
    if ($null -eq $clause) {
        $result.Error = 'no P2 primitive clause in section 11.4 of ' + $DocPath
        return $result
    }

    $names = @()
    foreach ($m in [regex]::Matches($clause, '`([^`]+)`')) {
        $tok = $m.Groups[1].Value
        $t = [regex]::Replace($tok, '<[^<>]*>', '')
        $k = $t.LastIndexOf('::')
        if ($k -ge 0) { $t = $t.Substring($k + 2) }
        $t = $t.Trim()
        if ($t -notmatch '^[A-Za-z_]\w*$') {
            $result.Error = 'the P2 clause of section 11.4 has a backticked token this script ' +
                            'cannot reduce to one identifier: `' + $tok + '`'
            return $result
        }
        if (-not ($names -contains $t)) { $names += $t }
    }
    if ($names.Count -eq 0) {
        $result.Error = 'the P2 clause of section 11.4 names no primitives'
        return $result
    }

    $result.Names = $names
    return $result
}

# ONE compiled alternation per primitive class, not one regex per name.
#
# Not a micro-optimisation: with 38 virtual names and 15 P2 names, per-name
# scanning is 53 passes over every function body in the tree, and it measured
# 14.9 SECONDS on this repository.  The gate runs this, and the self-test runs
# it twice more; a check that adds three quarters of a minute to every build is
# a check somebody deletes.  Folded into three passes it is under a second.
#
# `(?<!::)` rather than capturing the two preceding characters: a QUALIFIED call
# is statically bound and is not a P1 door (section 11.4), and a lookbehind
# expresses that without consuming input -- which matters, because a consuming
# prefix makes two adjacent calls overlap and silently drops the second.  A
# dropped door is an under-report, and under-reporting is the defect family.
function New-DoorMatcher {
    param([hashtable] $VirtualNames)

    $opt = [System.Text.RegularExpressions.RegexOptions]::Compiled
    # `(?!)` is the never-matching pattern.  It is here because the alternative
    # is far worse than it looks: an EMPTY name list builds `(?<n>)`, an empty
    # alternation, and `(?<!::)\b(?<n>)\s*\(` then matches EVERY parenthesis in
    # the tree with an empty door name.  Caught by the Platform-exemption
    # fixture, where the exemption legitimately empties the P1 set, and it
    # produced `first: P1 ` with nothing after it -- output that is not merely
    # over-red but meaningless, which is how a gate stops being read.
    $never = '(?!)'

    $p1 = $never
    if ($VirtualNames.Count -gt 0) {
        $p1 = '(?<!::)\b(?<n>' +
              (($VirtualNames.Keys | Sort-Object | ForEach-Object { [regex]::Escape($_) }) -join '|') +
              ')\s*\('
    }
    # ⚠ P2 CARRIES NO `(?<!::)`, AND P1 DOES.  The lookbehind's warrant is
    # section 11.4's sentence "a qualified call is not P1", and that sentence is
    # about VIRTUAL DISPATCH: `PushButton::sizeHint()` is statically bound, so it
    # cannot land in an application override.  P2 is not dispatch.  P2 is a list
    # of library functions known to reach application code, and
    # `Widget::setGeometry(r)` or `Base::relayout()` reaches it just as well
    # written qualified -- the qualification picks the implementation, it does
    # not stop the implementation running an application's onGeometryChanged.
    #
    # Copying the lookbehind onto P2 was therefore a category error, and the
    # direction it errs in is UNDER-REPORTING, which is this defect family
    # itself.  It is not a live defect today -- every qualified call in the tree
    # is a P1-family name -- which is exactly why it had to be fixed on the
    # argument rather than on a red light.
    $p2 = $never
    if ($script:P2Names.Count -gt 0) {
        $p2 = '\b(?<n>' +
              (($script:P2Names | Sort-Object | ForEach-Object { [regex]::Escape($_) }) -join '|') +
              ')\s*[<(]'
    }

    return @{
        P1 = New-Object System.Text.RegularExpressions.Regex($p1, $opt)
        P2 = New-Object System.Text.RegularExpressions.Regex($p2, $opt)
        P3 = New-Object System.Text.RegularExpressions.Regex('(\.|->)emit\s*\(', $opt)
    }
}

function Find-Doors {
    param([string] $Body, [hashtable] $Matcher)

    $doors = New-Object System.Collections.ArrayList

    # P1 -- generated from the declaration side.  `x->foo()`, `x.foo()` and a
    # bare `foo()` are all dispatch; `Base::foo()` is not.
    foreach ($m in $Matcher.P1.Matches($Body)) {
        [void] $doors.Add(@{ Kind = 'P1'; Name = $m.Groups['n'].Value; Offset = $m.Index })
    }
    # P2 -- named library functions known to reach application code.
    foreach ($m in $Matcher.P2.Matches($Body)) {
        [void] $doors.Add(@{ Kind = 'P2'; Name = $m.Groups['n'].Value; Offset = $m.Index })
    }
    # P3 -- signal emission.
    foreach ($m in $Matcher.P3.Matches($Body)) {
        [void] $doors.Add(@{ Kind = 'P3'; Name = 'emit'; Offset = $m.Index })
    }

    return ($doors | Sort-Object { $_.Offset })
}

# ---------------------------------------------------------------------------
# WHAT COUNTS AS A CURSOR ON THIS FRAME.
#
# Section 11.9 says "no DeathWatch in the body", and the first cut of this file
# took that literally because the literal reading is the redder one.  It was
# WRONG, and measurably so, not as a matter of taste: it reported
# Widget::dispatchMouse and Widget::dispatchKey as unguarded, and both of them
# carry a BubbleGuard AND re-test it after the door --
#
#     w->onMouse(local);              <- the door
#     if (local.accepted) { ... }
#     if (bubble.node() != w) return; <- the check
#
# -- which is the very shape REM3-G2/G3 ask for, written before REM3 existed.
# A lint that files a correct frame as a defect is how a lint gets muted, and a
# muted lint is the failure mode section 11.9 rejected the runtime counter for.
#
# So the predicate is "the frame holds a REM3 CURSOR", and all four of them are
# the same mechanism: LiveGuard<List> over a list that ~Widget cancels.
# DeathWatch was simply the only one in scope when 11.9 was written.
#
# ⚠ REGISTERED RESIDUE, because this is a WIDENING and widenings are how this
# family recurs: holding a cursor is not the same as CHECKING it, and this test
# cannot tell the two apart.  A frame that constructs a LayoutGuard for its own
# reasons and then walks through a door without asking alive() reads as guarded
# here.  Closing that needs the check to be tied to the door, which needs to
# know which pointer the door is dangerous to -- section 11.4's hazard clause,
# i.e. a compiler.  Recorded in section 12.4 rather than pretended away.
$script:CursorGuardPattern = '\b(DeathWatch|BubbleGuard|GeometryGuard|LayoutGuard)\b'

# Is there any code after this door's own statement, other than the closing
# brace?  "The door is the last statement" is section 11.9's one exclusion, and
# ScrollArea.cpp:165 / :174 and Widget.cpp:548 are the rows it exists for.
function Test-CodeFollowsDoor {
    param([string] $Body, [int] $DoorOffset)

    $depth = 0
    $i = $DoorOffset
    $n = $Body.Length
    while ($i -lt $n) {
        $c = $Body[$i]
        if ($c -eq '(' -or $c -eq '[' -or $c -eq '{') { $depth++ }
        elseif ($c -eq ')' -or $c -eq ']' -or $c -eq '}') {
            $depth--
            # Ran off the end of the body without a `;`: the door was the last
            # expression, e.g. `return layout_->measureFor(...)` has its `;`
            # first, so this only happens on malformed input.  Fail closed.
            if ($depth -lt 0) { return $true }
        }
        elseif ($c -eq ';' -and $depth -eq 0) { break }
        $i++
    }
    if ($i -ge $n) { return $true }
    $tail = $Body.Substring($i + 1)
    $tail = [regex]::Replace($tail, '[\s}]', '')
    return ($tail.Length -gt 0)
}

# ---------------------------------------------------------------------------
# THE ALLOWLIST: section 11.4 of the design document.  Parsed, never copied.
# ---------------------------------------------------------------------------
function Read-DoorAllowlist {
    param([string] $DocPath)

    $result = @{ Keys = @{}; Rows = 0; Error = '' }

    if (-not (Test-Path -LiteralPath $DocPath)) {
        $result.Error = 'design document not found: ' + $DocPath
        return $result
    }

    $lines = [System.IO.File]::ReadAllLines($DocPath, [System.Text.Encoding]::UTF8)

    $inSection = $false
    foreach ($line in $lines) {
        if ($line -match '^###\s+11\.4(\s|$)')  { $inSection = $true;  continue }
        if ($inSection -and $line -match '^###\s+11\.5(\s|$)') { $inSection = $false; break }
        if (-not $inSection) { continue }
        if ($line -notmatch '^\s*\|') { continue }

        $cells = $line.Split('|')
        # A markdown row splits to: '', c1, c2, ..., cN, ''
        if ($cells.Count -lt 6) { continue }
        $c = @()
        for ($k = 1; $k -lt $cells.Count - 1; $k++) { $c += $cells[$k].Trim() }
        if ($c.Count -lt 5) { continue }
        # Header and separator rows.
        if ($c[0] -match '^:?-{2,}') { continue }
        if ($c[0] -eq '#') { continue }

        $loc = $c[1]

        # Property 2: a row without BOTH a grade and a round archives nothing.
        # The main table is 8 columns (grade 6, round 7); the N table is 6
        # (grade 5, round 6).  Read them from the END so both shapes work: the
        # main table ends with an action column, the N table does not.
        $grade = ''; $round = ''
        if ($c.Count -ge 8)     { $grade = $c[5]; $round = $c[6] }
        elseif ($c.Count -eq 6) { $grade = $c[4]; $round = $c[5] }
        else                    { continue }
        if (-not $grade -or -not $round) { continue }

        $files = @()
        foreach ($m in [regex]::Matches($loc, '([A-Za-z_]\w*\.(?:cpp|hpp))')) {
            if (-not ($files -contains $m.Groups[1].Value)) { $files += $m.Groups[1].Value }
        }
        if ($files.Count -eq 0) { continue }

        # Function names: every backticked identifier in the location cell that
        # is not the file name itself.  `setContentSize`, `Layout::invalidate()`,
        # `contentRect()` all reduce to a bare name.
        $funcs = @()
        foreach ($m in [regex]::Matches($loc, '`([^`]+)`')) {
            $tok = $m.Groups[1].Value
            foreach ($idm in [regex]::Matches($tok, '(?<n>[A-Za-z_]\w*)\s*(\(\s*\))?\s*$')) {
                $nm = $idm.Groups['n'].Value
                if ($nm -match '\.(cpp|hpp)$') { continue }
                if ($tok -match '\.(cpp|hpp)') { continue }
                if (-not ($funcs -contains $nm)) { $funcs += $nm }
            }
        }
        if ($funcs.Count -eq 0) { continue }

        $result.Rows++
        foreach ($f in $files) {
            foreach ($fn in $funcs) {
                $result.Keys[($f + '|' + $fn)] = @{ Grade = $grade; Round = $round; Row = $c[0] }
            }
        }
    }

    if ($result.Rows -eq 0) { $result.Error = 'no parseable rows in section 11.4 of ' + $DocPath }
    return $result
}

# ---------------------------------------------------------------------------
# Two extra machine predicates that section 11.4 / 11.9 asked for BY NAME, kept
# here rather than in a second tool because they answer the same question --
# "is the register still telling the truth?" -- and because a check nobody runs
# is not a check.
# ---------------------------------------------------------------------------

# Section 11.4's exemption for Platform.hpp's 21 virtuals rests on ONE
# structural fact: there is no way to install an application's implementation.
# The document says, verbatim, "this grep should go into section 11.9's lint:
# it is a two-line machine predicate, more reliable than a paragraph of
# exemption prose."  The day an install point appears, those 21 enter the table.
function Test-NoPlatformInstallPoint {
    param([string] $Root)
    $hits = New-Object System.Collections.ArrayList
    foreach ($dir in @('include', 'src')) {
        $d = Join-Path $Root $dir
        if (-not (Test-Path -LiteralPath $d)) { continue }
        # Extension tested rather than -Include, for the reason recorded on
        # Get-SourceFiles: -Include does nothing next to -LiteralPath -Recurse,
        # so this loop has been reading every file under include\ and src\,
        # comment-stripping .md and .natvis as if they were C++.  Harmless for
        # THIS predicate -- a wider net cannot make it miss an install point --
        # but a filter that does not filter is not a thing to leave lying about.
        foreach ($f in (Get-ChildItem -LiteralPath $d -Recurse -File |
                        Where-Object { $_.Extension -in @('.hpp', '.cpp', '.h', '.cc') })) {
            $clean = Get-CleanText $f.FullName
            if ($clean -match '\b(setPlatform|installPlatform)\b') {
                [void] $hits.Add($f.FullName.Substring($Root.Length).TrimStart('\'))
            }
        }
    }
    return $hits
}

# EVERY .bat IN THIS TREE MUST STAY PURE ASCII.  This is verify.bat's own rule,
# and it is here because a rule written in a comment is a rule the next tool to
# rewrite the file has never read.
#
# THE MECHANISM, MEASURED RATHER THAN REPEATED.  cmd.exe seeks in a batch file
# by BYTE OFFSET while accounting for what it consumed in CHARACTERS.  The full
# truth table, run on this machine (160 filler lines, one echo, four builds of
# the same file):
#
#     CRLF + UTF-8 multibyte  -> correct
#     CRLF + GBK  multibyte   -> correct
#     LF   + pure ASCII       -> correct
#     LF   + UTF-8 multibyte  -> BROKEN.  The parser resumes mid-line 160 lines
#                                further up and runs the fragment `ine` as a
#                                command, which is exactly the reported symptom.
#
# So it takes BOTH conditions.  verify.bat's note describes it as a property of
# LF; that is half of it, and the half that matters here is the OTHER one.
#
# WHY THIS CHECKS ASCII AND NOT LINE ENDINGS.  All four .bat files in this tree
# are bare-LF today, so the ASCII half is the only thing keeping them working --
# which makes it the half worth enforcing.  Converting them to CRLF was
# considered and rejected on a measurement: core.autocrlf is `true` here and
# there is no .gitattributes, so a CRLF working tree normalises straight back to
# LF in the index.  `git status` calls the file modified and `git diff` shows
# ZERO lines changed -- the conversion cannot be reviewed and cannot be
# committed.  The landable form of that fix is one line of .gitattributes
# (`*.bat text eol=crlf`), which changes what every checkout in the project
# produces and is therefore not a thing a lint should decide by itself.
#
# AND NOTE WHAT THIS CHECK CANNOT DO: it runs FROM verify.bat, so it cannot
# protect verify.bat from a drift that has already happened -- cmd would
# mis-execute the file long before reaching this step.  It protects the NEXT
# run, by failing the gate the moment a non-ASCII byte lands in any .bat.  That
# is why it tests the PRECONDITION and not the symptom.
# ---------------------------------------------------------------------------
# IS THE GATE STILL PLUGGED IN?
#
# The two machine checkers in this tree -- this lint and tools\classify-asan.ps1
# -- are the only things standing between, respectively, an unguarded door and a
# release, and a use-after-free and a release.  Both of them prove themselves
# against fixtures before they speak.  NEITHER OF THEM WAS WATCHING WHETHER THE
# GATE STILL CALLS THEM.
#
# Measured, and it is worse than it sounds: delete `call :lint_doors` from
# verify.bat:55, or `call :classify_asan` from :146, and verify.bat still runs
# all six steps, still prints its six-row summary, and still prints
#
#     [ok] gate is GREEN
#
# because both checkers redden the gate by SETTING A VARIABLE FROM INSIDE a
# subroutine that is no longer called.  A checker that is not invoked fails
# open, silently, and the run that dropped it looks exactly like a clean one.
#
# So this is the third named machine predicate, and it is deliberately the
# stupidest one in the file: strip the batch comments, then look for the two
# calls and the two labels they land on.  A `call` to a label that does not
# exist is not a call either -- cmd prints "cannot find the batch label" and
# carries on to the next line with the rest of the run untouched.
#
# THE COMMENTS ARE STRIPPED FIRST for the same reason Clear-CppNoise exists:
# verify.bat's `rem` blocks are longer than its code and they QUOTE THESE VERY
# LINES ("...prints its own [ ok ] / [FAIL] line", "inside step [1/6]").  A raw
# match would be satisfied by a comment describing the call that somebody just
# deleted, which is the most specific way this check could be useless.
#
# AND THE FILE MUST EXIST.  A missing verify.bat is red, not skipped: "the gate
# is not there" is not a green condition.
function Test-GateStillCallsItsCheckers {
    param([string] $Root)

    $missing = New-Object System.Collections.ArrayList
    $bat = Join-Path $Root 'verify.bat'
    if (-not (Test-Path -LiteralPath $bat)) {
        [void] $missing.Add('verify.bat is not there at all')
        return $missing
    }

    $text = [System.IO.File]::ReadAllText($bat)
    $kept = New-Object System.Collections.ArrayList
    foreach ($line in ($text -split "`r`n|`n|`r")) {
        $t = $line.Trim()
        if ($t -match '^(?i)rem(\s|$)') { continue }
        if ($t -match '^::') { continue }
        [void] $kept.Add($line)
    }
    $code = ($kept -join "`n")

    foreach ($pair in @(
        @{ Label = 'lint_doors';   What = 'the door-coverage lint (this script)' },
        @{ Label = 'classify_asan'; What = 'the ASan report classifier' })) {
        if ($code -notmatch ('(?im)^\s*call\s+:' + $pair.Label + '\s*$')) {
            [void] $missing.Add(('verify.bat never calls :{0} -- {1} is not run' -f $pair.Label, $pair.What))
        }
        elseif ($code -notmatch ('(?im)^\s*:' + $pair.Label + '\s*$')) {
            [void] $missing.Add(('verify.bat calls :{0} but has no such label -- cmd skips it' -f $pair.Label))
        }
    }
    return $missing
}

function Test-BatchFileHygiene {
    param([string] $Root)
    $bad = New-Object System.Collections.ArrayList
    foreach ($f in Get-ChildItem -LiteralPath $Root -File -Filter *.bat) {
        $bytes = [System.IO.File]::ReadAllBytes($f.FullName)
        $lfNoCr   = 0
        $nonAscii = 0
        for ($i = 0; $i -lt $bytes.Length; $i++) {
            if ($bytes[$i] -gt 127) { $nonAscii++ }
            if ($bytes[$i] -eq 10) {
                if ($i -eq 0 -or $bytes[$i - 1] -ne 13) { $lfNoCr++ }
            }
        }
        if ($nonAscii -gt 0) {
            [void] $bad.Add(@{ Name = $f.Name; BareLf = $lfNoCr; NonAscii = $nonAscii })
        }
    }
    return $bad
}

# ---------------------------------------------------------------------------
# The lint proper, as a function that RETURNS its exit code.  The script body at
# the bottom is the only place `exit` appears -- same shape as
# tools\classify-asan.ps1, and for the same reason: the self-test drives this
# in-process.
# ---------------------------------------------------------------------------
function Invoke-LintDoorCoverage {
    param(
        [string] $RepoRoot = '',
        [string] $DocPath = '',
        [string[]] $SrcDirs = @(),
        [string] $IncludeDir = '',
        [int] $MaxList = 40,
        [switch] $Quiet,
        [switch] $Silent
    )

    $script:Emitted = New-Object System.Collections.ArrayList
    $script:Silent  = [bool] $Silent

    try {
        if (-not $RepoRoot) { $RepoRoot = Split-Path -Parent $script:LintDir }
        if (-not $DocPath)  { $DocPath = Join-Path $RepoRoot 'docs\iterations\02-layout-engine.md' }
        if (-not $IncludeDir) { $IncludeDir = Join-Path $RepoRoot 'include\geeyoou' }
        # THE CANDIDATE SIDE HAS THE SAME SCAN ROOT AS THE DECLARATION SIDE, and
        # it did not until the fourth security review found this.  Property 4's
        # second paragraph -- "the scan root is the whole of include\geeyoou, not
        # Widget.hpp" -- was fixed on the DECLARATION side only; the CANDIDATE
        # side was rooted at `src`, and the library's code is not all in `src`.
        # Same hole, second appearance, on the other side of the same script.
        # Measured cost of the omission: AppWindow::setContent and
        # WindowHeader::addTrailingItem, a P2 door each with writes through
        # `this` after it, structurally invisible.
        if ($SrcDirs.Count -eq 0) {
            $SrcDirs = @((Join-Path $RepoRoot 'src'), (Join-Path $RepoRoot 'include'))
        }

        # -- property 4: the P1 name table, generated from the declaration side --
        if (-not (Test-Path -LiteralPath $IncludeDir)) {
            Write-LintLine ('  [lint-doors] include root not found: ' + $IncludeDir)
            return $EXIT_INTERNAL
        }
        $headers = @(Get-ChildItem -LiteralPath $IncludeDir -Recurse -File -Filter *.hpp | ForEach-Object { $_.FullName })
        if ($headers.Count -eq 0) {
            Write-LintLine ('  [lint-doors] no headers under ' + $IncludeDir)
            return $EXIT_INTERNAL
        }
        $virtualsAll = Get-VirtualNames -HeaderPaths $headers
        # The Platform exemption, gated below by Test-NoPlatformInstallPoint.
        $virtuals = Remove-PlatformOnlyNames -Names $virtualsAll
        $exempted = $virtualsAll.Count - $virtuals.Count

        # -- the P2 half of the predicate, also from the document ------------
        $p2 = Read-DoorPrimitivesP2 -DocPath $DocPath
        if ($p2.Error) {
            Write-LintLine ('  [lint-doors] ' + $p2.Error)
            return $EXIT_INTERNAL
        }
        $script:P2Names = $p2.Names

        $matcher = New-DoorMatcher -VirtualNames $virtuals

        # -- the allowlist --------------------------------------------------
        $allow = Read-DoorAllowlist -DocPath $DocPath
        if ($allow.Error) {
            Write-LintLine ('  [lint-doors] ' + $allow.Error)
            return $EXIT_INTERNAL
        }

        # -- the candidate set ----------------------------------------------
        $candidates = New-Object System.Collections.ArrayList
        $guarded    = 0
        $scanned    = 0
        $broken     = New-Object System.Collections.ArrayList

        foreach ($dir in $SrcDirs) {
            if (-not (Test-Path -LiteralPath $dir)) { continue }
            foreach ($f in (Get-SourceFiles -Dir $dir)) {
                $scanned++
                $clean = Get-CleanText $f.FullName
                $idx   = New-LineIndex $clean
                $leaf  = $f.Name

                foreach ($fn in (Split-CppFunctions -Clean $clean)) {
                    if ($fn.Unbalanced) {
                        [void] $broken.Add(($leaf + ' :: ' + $fn.Name))
                        continue
                    }
                    $body = $clean.Substring($fn.BodyStart, $fn.BodyEnd - $fn.BodyStart)
                    $doors = @(Find-Doors -Body $body -Matcher $matcher)
                    if ($doors.Count -eq 0) { continue }

                    $live = @($doors | Where-Object { Test-CodeFollowsDoor -Body $body -DoorOffset $_.Offset })
                    if ($live.Count -eq 0) { continue }

                    if ($body -match $script:CursorGuardPattern) { $guarded++; continue }

                    # NOT $home: that is a read-only automatic variable in
                    # PowerShell and assigning it throws, which this script then
                    # catches and turns into exit 3 -- a red gate for a reason
                    # that has nothing to do with doors.
                    $key = $leaf + '|' + $fn.Name
                    $homeRow = $null
                    if ($allow.Keys.ContainsKey($key)) { $homeRow = $allow.Keys[$key] }

                    $first = $live[0]
                    [void] $candidates.Add(@{
                        File = $leaf
                        Func = $fn.Name
                        Qualified = $fn.Qualified
                        Line = (Get-LineOf -LineStarts $idx -Offset ($fn.BodyStart + $first.Offset))
                        Kinds = (($live | ForEach-Object { $_.Kind }) | Sort-Object -Unique) -join '/'
                        Doors = $live.Count
                        Sample = ($first.Kind + ' ' + $first.Name)
                        Home = $homeRow
                    })
                }
            }
        }

        $unarchived = @($candidates | Where-Object { $null -eq $_.Home })
        $archived   = @($candidates | Where-Object { $null -ne $_.Home })

        # -- the two named machine predicates ---------------------------------
        $platformHits = @(Test-NoPlatformInstallPoint -Root $RepoRoot)
        $batBad       = @(Test-BatchFileHygiene -Root $RepoRoot)
        $gateUnwired  = @(Test-GateStillCallsItsCheckers -Root $RepoRoot)

        # -- report -----------------------------------------------------------
        # The P2 COUNT is printed, not just the archived-row count, and the
        # reason is the direction each one can drift in.  Losing an allowlist
        # row makes the gate redder; losing a P2 primitive makes it GREENER, by
        # deleting a class of candidate, and nothing else in this script can see
        # that happen.  A number in the gate log is what makes the shrink show
        # up in a diff of two runs.
        Write-LintLine ('  [lint-doors] {0} virtual name(s) from {1} header(s) ({2} Platform-only, exempt) + {3} P2 primitive(s) from section 11.4; {4} source file(s); section 11.4 archived {5} row(s)' -f `
            $virtuals.Count, $headers.Count, $exempted, $script:P2Names.Count, $scanned, $allow.Rows)
        Write-LintLine ('  [lint-doors] candidates: {0} guarded (DeathWatch), {1} archived, {2} UNARCHIVED' -f `
            $guarded, $archived.Count, $unarchived.Count)

        $red = $false

        if ($broken.Count -gt 0) {
            $red = $true
            Write-LintLine '  [lint-doors] FAIL: function bodies this script could not delimit (fail closed):'
            foreach ($b in $broken) { Write-LintLine ('      ' + $b) }
        }

        if ($unarchived.Count -gt 0) {
            $red = $true
            Write-LintLine '  [lint-doors] FAIL: candidates with no home. Guard the frame, or register it'
            Write-LintLine '               in section 11.4 with a reason, a grade and a round:'
            $shown = 0
            foreach ($u in ($unarchived | Sort-Object File, Func)) {
                $shown++
                if ($shown -gt $MaxList) { continue }
                Write-LintLine ('      {0}::{1}  line {2}  [{3}, {4} door(s), first: {5}]' -f `
                    $u.File, $u.Func, $u.Line, $u.Kinds, $u.Doors, $u.Sample)
            }
            if ($unarchived.Count -gt $MaxList) {
                Write-LintLine ('      ... and {0} more.' -f ($unarchived.Count - $MaxList))
            }
        }

        if ($platformHits.Count -gt 0) {
            $red = $true
            Write-LintLine '  [lint-doors] FAIL: an implementation install point for Platform now exists, so'
            Write-LintLine '               section 11.4 s exemption for Platform.hpp s 21 virtuals has lapsed.'
            Write-LintLine '               Put them in the table, graded one by one:'
            foreach ($h in $platformHits) { Write-LintLine ('      ' + $h) }
        }

        if ($gateUnwired.Count -gt 0) {
            $red = $true
            Write-LintLine '  [lint-doors] FAIL: the gate no longer invokes one of its own checkers, so that'
            Write-LintLine '               checker fails OPEN -- verify.bat runs all six steps and prints'
            Write-LintLine '               "gate is GREEN" with nothing watching. Put the call back:'
            foreach ($g in $gateUnwired) { Write-LintLine ('      ' + $g) }
        }

        if ($batBad.Count -gt 0) {
            $red = $true
            Write-LintLine '  [lint-doors] FAIL: a batch file is no longer pure ASCII. cmd.exe mis-executes a'
            Write-LintLine '               batch file that has BOTH bare-LF endings AND multi-byte characters,'
            Write-LintLine '               and every .bat here is bare-LF, so ASCII is what keeps them working.'
            Write-LintLine '               Move the text into a .ps1, as tools\test-classify-asan.ps1 does:'
            foreach ($b in $batBad) {
                Write-LintLine ('      {0}: {1} non-ASCII byte(s), {2} bare-LF line(s)' -f $b.Name, $b.NonAscii, $b.BareLf)
            }
        }

        if (-not $Quiet -and $archived.Count -gt 0) {
            Write-LintLine '  [lint-doors] archived candidates (section 11.4 has a row for each):'
            foreach ($a in ($archived | Sort-Object File, Func)) {
                Write-LintLine ('      {0}::{1}  line {2}  [{3}]  -> row {4}, {5}, {6}' -f `
                    $a.File, $a.Func, $a.Line, $a.Kinds, $a.Home.Row, $a.Home.Grade, $a.Home.Round)
            }
        }

        if ($red) { return $EXIT_UNCOVERED }
        return $EXIT_COVERED
    }
    catch {
        Write-LintLine ('  [lint-doors] INTERNAL ERROR, failing closed: ' + $_.Exception.Message)
        Write-LintLine ('  [lint-doors] at: ' + $_.InvocationInfo.PositionMessage)
        return $EXIT_INTERNAL
    }
}


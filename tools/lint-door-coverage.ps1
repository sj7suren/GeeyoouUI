# ---------------------------------------------------------------------------
# Blank out comments and string / character literals, PRESERVING LENGTH and
# every newline, so that every offset computed afterwards still maps to the
# original line number.
#
# This is not a nicety in this repository.  The comments here are longer than
# the code and they QUOTE THE DOOR NAMES: Window.cpp's header says
# "onFocusChanged is a protected virtual: a P1 door", AppWindow.cpp's says
# "header_->setGeometry".  Scanning raw text would report a door in a comment
# that exists to explain a door, which is a special kind of useless.
# ---------------------------------------------------------------------------
function Clear-CppNoise {
    param([string] $Text)

    $out = New-Object System.Text.StringBuilder
    $n = $Text.Length
    $i = 0
    while ($i -lt $n) {
        $c = $Text[$i]
        $d = ''
        if ($i + 1 -lt $n) { $d = $Text[$i + 1] }

        if ($c -eq '/' -and $d -eq '/') {
            while ($i -lt $n -and $Text[$i] -ne "`n") {
                if ($Text[$i] -eq "`r") { [void] $out.Append("`r") } else { [void] $out.Append(' ') }
                $i++
            }
            continue
        }
        if ($c -eq '/' -and $d -eq '*') {
            [void] $out.Append('  '); $i += 2
            while ($i -lt $n) {
                if ($Text[$i] -eq '*' -and $i + 1 -lt $n -and $Text[$i + 1] -eq '/') {
                    [void] $out.Append('  '); $i += 2; break
                }
                if ($Text[$i] -eq "`n") { [void] $out.Append("`n") }
                elseif ($Text[$i] -eq "`r") { [void] $out.Append("`r") }
                else { [void] $out.Append(' ') }
                $i++
            }
            continue
        }
        if ($c -eq '"' -or $c -eq "'") {
            $quote = $c
            [void] $out.Append(' '); $i++
            while ($i -lt $n) {
                if ($Text[$i] -eq '\') {
                    [void] $out.Append('  ')
                    $i += 2
                    continue
                }
                if ($Text[$i] -eq $quote) { [void] $out.Append(' '); $i++; break }
                if ($Text[$i] -eq "`n") { [void] $out.Append("`n") }
                elseif ($Text[$i] -eq "`r") { [void] $out.Append("`r") }
                else { [void] $out.Append(' ') }
                $i++
            }
            continue
        }

        [void] $out.Append($c)
        $i++
    }
    return $out.ToString()
}

# Comment-stripping the same file twice is pure waste, and this script used to
# do exactly that: once to collect virtual names or door candidates, and once
# more for the Platform install-point predicate.  Keyed on path AND last-write
# time, so a fixture the self-test rewrites between cases is never served stale.
$script:CleanCache = @{}
function Get-CleanText {
    param([string] $Path)
    $stamp = [System.IO.File]::GetLastWriteTimeUtc($Path).Ticks
    $key = $Path + '|' + $stamp
    if ($script:CleanCache.ContainsKey($key)) { return $script:CleanCache[$key] }
    $v = Clear-CppNoise ([System.IO.File]::ReadAllText($Path))
    $script:CleanCache[$key] = $v
    return $v
}

# Every translation-unit-shaped file under a scan root.
#
# ⚠ NOT `Get-ChildItem -LiteralPath ... -Recurse -Include *.cpp`, which is what
# this script used and which DOES NOT FILTER.  Measured on this machine,
# PowerShell 5.1.19041:
#
#     Get-ChildItem -LiteralPath <include> -Recurse -File -Include *.cpp  -> 59
#     Get-ChildItem -Path        <include> -Recurse -File -Include *.cpp  ->  0
#
# -Include is matched against the LiteralPath and silently ignored for the
# recursion, so the "only .cpp" in the old scan was not a filter at all -- it
# was `src` happening to contain almost nothing else.  It contains one thing
# else (src\render\VectorPathImpl.hpp), which was therefore being scanned by
# accident, and the day somebody drops a .md or a .natvis in there it would
# have been read as C++ and reported as an unbalanced body.  A filter that does
# not filter is the same defect as a lint that does not lint.
#
# -Filter is not the fix either: the FileSystem provider's wildcard still
# carries 8.3 semantics, so `*.cpp` matches `foo.cppm`.  The extension is
# tested directly instead; this tree is 106 files and the walk is not the cost.
function Get-SourceFiles {
    param([string] $Dir)
    return @(Get-ChildItem -LiteralPath $Dir -Recurse -File |
             Where-Object { $_.Extension -eq '.cpp' -or $_.Extension -eq '.hpp' } |
             Sort-Object FullName)
}

# Offset -> 1-based line number.  Built once per file.
function New-LineIndex {
    param([string] $Text)
    $starts = New-Object System.Collections.ArrayList
    [void] $starts.Add(0)
    for ($i = 0; $i -lt $Text.Length; $i++) {
        if ($Text[$i] -eq "`n") { [void] $starts.Add($i + 1) }
    }
    return $starts
}
function Get-LineOf {
    param($LineStarts, [int] $Offset)
    $lo = 0; $hi = $LineStarts.Count - 1
    while ($lo -lt $hi) {
        $mid = [int](($lo + $hi + 1) / 2)
        if ($LineStarts[$mid] -le $Offset) { $lo = $mid } else { $hi = $mid - 1 }
    }
    return $lo + 1
}

# ---------------------------------------------------------------------------
# THE P1 INPUT: every virtual member function name declared anywhere under
# include\geeyoou.  Property 4.  Destructors are excluded -- a destructor is not
# a door in this family's sense; it is the thing the doors are dangerous
# BECAUSE of.
#
# `override` declarations are collected too: a subclass override is a virtual
# whether or not the word `virtual` is repeated, and SelectBase.hpp writes them
# both ways.
# ---------------------------------------------------------------------------
function Get-VirtualNames {
    param([string[]] $HeaderPaths)

    $names = @{}
    foreach ($p in $HeaderPaths) {
        $clean = Get-CleanText $p
        foreach ($line in ($clean -split "`r`n|`n|`r")) {
            $isVirtual  = ($line -match '(^|[^\w])virtual\s')
            $isOverride = ($line -match '\)\s*(const\s*)?(noexcept\s*)?override\b')
            if (-not $isVirtual -and -not $isOverride) { continue }
            # The declared name is the identifier in front of the first
            # parameter list on the line.
            $m = [regex]::Match($line, '(?<tilde>~\s*)?(?<name>[A-Za-z_]\w*)\s*\(')
            if (-not $m.Success) { continue }
            # NOT just `virtual ~`.  Half of this tree writes its destructor as
            # `~Foo() override;` with no `virtual` on the line at all, and a
            # `virtual ~`-only filter let five of them through as if `AppWindow`,
            # `Widget`, `Window`, `MenuButton` and `SelectBase` were door names --
            # which then matched every `new Widget(` in the library.
            if ($m.Groups['tilde'].Success) { continue }
            $nm = $m.Groups['name'].Value
            if ($nm -in @('if', 'for', 'while', 'switch', 'return', 'sizeof', 'catch')) { continue }
            if (-not $names.ContainsKey($nm)) { $names[$nm] = New-Object System.Collections.ArrayList }
            $leaf = Split-Path -Leaf $p
            if (-not $names[$nm].Contains($leaf)) { [void] $names[$nm].Add($leaf) }
        }
    }
    return $names
}

# Section 11.4's "looked at it, does not need shutting" list exempts the 21
# non-destructor virtuals of platform\Platform.hpp, and the reason is
# STRUCTURAL rather than a usage observation: Platform& platform() is the only
# way in the library to obtain an implementation, and there is no setter, no
# registration point and no factory, so those virtuals cannot be overridden by
# an application -- there is no interface to do it through.
#
# Applied here, and applied MECHANICALLY, because the alternative is a name
# collision that makes the lint stupid: PlatformWindow declares restore(),
# show(), invalidate(), close() and thirteen more, and leaving them in the P1
# set makes every painter.restore() and every Layout::invalidate() look like a
# door.  A name that is ALSO declared outside Platform.hpp stays in -- close()
# is a SelectBase virtual as well, and that one is a genuine door.
#
# THE EXEMPTION IS GATED, NOT ASSUMED: Test-NoPlatformInstallPoint runs on every
# invocation and reddens the gate the day an install point appears, at which
# point these names come back and get graded one by one.  That gate is the whole
# reason this is allowed to be a subtraction.
function Remove-PlatformOnlyNames {
    param([hashtable] $Names)
    $out = @{}
    foreach ($k in $Names.Keys) {
        $headers = @($Names[$k])
        $nonPlatform = @($headers | Where-Object { $_ -ne 'Platform.hpp' })
        if ($nonPlatform.Count -eq 0) { continue }
        $out[$k] = $Names[$k]
    }
    return $out
}

# ---------------------------------------------------------------------------
# Approximate function-body splitting: brace balance plus a header test.  Not a
# parser, and section 11.9 says so up front.  What it must never do is MISS a
# body, because a missed body is a missed candidate; over-splitting only costs
# noise.
# ---------------------------------------------------------------------------
$script:NotAFunctionHead = '^(if|for|while|switch|catch|do|else|return|namespace|class|struct|union|enum|extern|template|using|typedef|public|private|protected)\b'

function Test-FunctionHeader {
    param([string] $Snippet)

    $s = $Snippet.Trim()
    if (-not $s) { return $null }

    # A `template <...>` prefix, STRIPPED BEFORE the NotAFunctionHead test.
    #
    # This is the second half of the candidate-side scan-root hole, and without
    # it widening the root buys nothing.  `template` is in NotAFunctionHead, so
    # every template body read as "not a function": the splitter descended into
    # it looking for functions INSIDE, found none, and the whole body -- doors
    # and all -- was never scanned.  Measured on AppWindow.hpp: the splitter
    # reported header/content/isBorderVisible and NOT setContent, whose body is
    # `add<T>()` (a P2 door) followed by two writes through `this`.
    #
    # Brace-counting the angle brackets rather than a lazy `.*?>`: `template
    # <class T, std::vector<int> V>` has a nested pair, and the lazy form stops
    # at the first `>` and leaves `V>` in front of the name.
    while ($s -match '^template\s*<') {
        $k = $s.IndexOf('<')
        $d = 0
        $end = -1
        for ($q = $k; $q -lt $s.Length; $q++) {
            if ($s[$q] -eq '<') { $d++ }
            elseif ($s[$q] -eq '>') { $d--; if ($d -eq 0) { $end = $q; break } }
        }
        if ($end -lt 0) { return $null }
        $s = $s.Substring($end + 1).Trim()
        if (-not $s) { return $null }
    }

    # `} else {`, `namespace detail {`, `class Foo : public Bar {` ...
    if ($s -match $script:NotAFunctionHead) { return $null }
    # An initialiser, not a definition.  `==` / `!=` / `<=` / `>=` are not
    # assignments, and `= default` / `= delete` / `= 0` never precede a body.
    $noCmp = [regex]::Replace($s, '[=!<>]=', '@@')
    if ($noCmp -match '=') { return $null }
    # A lambda body, a designated initialiser, an array of structs.
    if ($s -match '\]\s*(\([^)]*\))?\s*(mutable)?\s*(->[^{]*)?$' -and $s -match '\[') { return $null }

    $open = $s.IndexOf('(')
    if ($open -lt 0) { return $null }
    $head = $s.Substring(0, $open)
    $m = [regex]::Match($head, '(?<q>[A-Za-z_]\w*(\s*::\s*[A-Za-z_]\w*)*)\s*$')
    if (-not $m.Success) { return $null }

    $qual = [regex]::Replace($m.Groups['q'].Value, '\s+', '')
    $name = $qual
    $k = $qual.LastIndexOf('::')
    if ($k -ge 0) { $name = $qual.Substring($k + 2) }
    if (-not $name) { return $null }
    if ($name -match $script:NotAFunctionHead) { return $null }
    return @{ Name = $name; Qualified = $qual }
}

function Split-CppFunctions {
    param([string] $Clean)

    $funcs = New-Object System.Collections.ArrayList
    $n = $Clean.Length
    # Offset just past the last `;`, `{` or `}` seen at the current point --
    # i.e. where the snippet in front of the next `{` starts.
    $snippetStart = 0
    $i = 0
    # Stack of open braces we have descended into WITHOUT calling them a
    # function (namespaces, classes, structs, initialiser lists).
    $depth = 0

    while ($i -lt $n) {
        $c = $Clean[$i]
        if ($c -eq ';' -or $c -eq '}') { $snippetStart = $i + 1; $i++; continue }
        if ($c -ne '{') { $i++; continue }

        $snippet = $Clean.Substring($snippetStart, $i - $snippetStart)
        $hdr = Test-FunctionHeader $snippet

        if ($null -eq $hdr) {
            # Not a function: descend, keep looking inside (a class body in a
            # .cpp holds member function definitions, and Widget.cpp has three).
            $snippetStart = $i + 1
            $depth++
            $i++
            continue
        }

        # A function.  Find its matching close brace, record the body, and
        # resume AFTER it -- we do not look for functions inside a function.
        $d = 0
        $j = $i
        while ($j -lt $n) {
            if ($Clean[$j] -eq '{') { $d++ }
            elseif ($Clean[$j] -eq '}') {
                $d--
                if ($d -eq 0) { break }
            }
            $j++
        }
        if ($j -ge $n) {
            # Unbalanced.  Fail closed: report it and stop scanning this file.
            [void] $funcs.Add(@{
                Name = $hdr.Name; Qualified = $hdr.Qualified
                HeadOffset = $snippetStart; BodyStart = $i + 1; BodyEnd = $n
                Unbalanced = $true
            })
            break
        }

        [void] $funcs.Add(@{
            Name = $hdr.Name; Qualified = $hdr.Qualified
            HeadOffset = $snippetStart; BodyStart = $i + 1; BodyEnd = $j
            Unbalanced = $false
        })
        $i = $j + 1
        $snippetStart = $i
    }
    return $funcs
}


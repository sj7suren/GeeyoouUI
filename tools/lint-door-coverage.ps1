# Section 11.4's exemption for Platform.hpp's 21 virtuals rests on ONE
# structural fact: there is no way to install an application's implementation.
# The document says, verbatim, "this grep should go into section 11.9's lint:
# it is a two-line machine predicate, more reliable than a paragraph of
# exemption prose."  The day an install point appears, those 21 enter the table.
function Test-NoPlatformInstallPoint {
    param([string] $Root)
    $hits = New-Object System.Collections.ArrayList
    foreach ($dir in @('include', 'src')) {
        $d = Join-Path $Root $dir
        if (-not (Test-Path -LiteralPath $d)) { continue }
        foreach ($f in Get-ChildItem -LiteralPath $d -Recurse -File -Include *.hpp, *.cpp, *.h, *.cc) {
            $clean = Get-CleanText $f.FullName
            if ($clean -match '\b(setPlatform|installPlatform)\b') {
                [void] $hits.Add($f.FullName.Substring($Root.Length).TrimStart('\'))
            }
        }
    }
    return $hits
}

# EVERY .bat IN THIS TREE MUST STAY PURE ASCII.  This is verify.bat's own rule,
# and it is here because a rule written in a comment is a rule the next tool to
# rewrite the file has never read.
#
# THE MECHANISM, MEASURED RATHER THAN REPEATED.  cmd.exe seeks in a batch file
# by BYTE OFFSET while accounting for what it consumed in CHARACTERS.  The full
# truth table, run on this machine (160 filler lines, one echo, four builds of
# the same file):
#
#     CRLF + UTF-8 multibyte  -> correct
#     CRLF + GBK  multibyte   -> correct
#     LF   + pure ASCII       -> correct
#     LF   + UTF-8 multibyte  -> BROKEN.  The parser resumes mid-line 160 lines
#                                further up and runs the fragment `ine` as a
#                                command, which is exactly the reported symptom.
#
# So it takes BOTH conditions.  verify.bat's note describes it as a property of
# LF; that is half of it, and the half that matters here is the OTHER one.
#
# WHY THIS CHECKS ASCII AND NOT LINE ENDINGS.  All four .bat files in this tree
# are bare-LF today, so the ASCII half is the only thing keeping them working --
# which makes it the half worth enforcing.  Converting them to CRLF was
# considered and rejected on a measurement: core.autocrlf is `true` here and
# there is no .gitattributes, so a CRLF working tree normalises straight back to
# LF in the index.  `git status` calls the file modified and `git diff` shows
# ZERO lines changed -- the conversion cannot be reviewed and cannot be
# committed.  The landable form of that fix is one line of .gitattributes
# (`*.bat text eol=crlf`), which changes what every checkout in the project
# produces and is therefore not a thing a lint should decide by itself.
#
# AND NOTE WHAT THIS CHECK CANNOT DO: it runs FROM verify.bat, so it cannot
# protect verify.bat from a drift that has already happened -- cmd would
# mis-execute the file long before reaching this step.  It protects the NEXT
# run, by failing the gate the moment a non-ASCII byte lands in any .bat.  That
# is why it tests the PRECONDITION and not the symptom.
function Test-BatchFileHygiene {
    param([string] $Root)
    $bad = New-Object System.Collections.ArrayList
    foreach ($f in Get-ChildItem -LiteralPath $Root -File -Filter *.bat) {
        $bytes = [System.IO.File]::ReadAllBytes($f.FullName)
        $lfNoCr   = 0
        $nonAscii = 0
        for ($i = 0; $i -lt $bytes.Length; $i++) {
            if ($bytes[$i] -gt 127) { $nonAscii++ }
            if ($bytes[$i] -eq 10) {
                if ($i -eq 0 -or $bytes[$i - 1] -ne 13) { $lfNoCr++ }
            }
        }
        if ($nonAscii -gt 0) {
            [void] $bad.Add(@{ Name = $f.Name; BareLf = $lfNoCr; NonAscii = $nonAscii })
        }
    }
    return $bad
}

# ---------------------------------------------------------------------------
# The lint proper, as a function that RETURNS its exit code.  The script body at
# the bottom is the only place `exit` appears -- same shape as
# tools\classify-asan.ps1, and for the same reason: the self-test drives this
# in-process.
# ---------------------------------------------------------------------------
function Invoke-LintDoorCoverage {
    param(
        [string] $RepoRoot = '',
        [string] $DocPath = '',
        [string[]] $SrcDirs = @(),
        [string] $IncludeDir = '',
        [int] $MaxList = 40,
        [switch] $Quiet,
        [switch] $Silent
    )

    $script:Emitted = New-Object System.Collections.ArrayList
    $script:Silent  = [bool] $Silent

    try {
        if (-not $RepoRoot) { $RepoRoot = Split-Path -Parent $script:LintDir }
        if (-not $DocPath)  { $DocPath = Join-Path $RepoRoot 'docs\iterations\02-layout-engine.md' }
        if (-not $IncludeDir) { $IncludeDir = Join-Path $RepoRoot 'include\geeyoou' }
        if ($SrcDirs.Count -eq 0) { $SrcDirs = @((Join-Path $RepoRoot 'src')) }

        # -- property 4: the P1 name table, generated from the declaration side --
        if (-not (Test-Path -LiteralPath $IncludeDir)) {
            Write-LintLine ('  [lint-doors] include root not found: ' + $IncludeDir)
            return $EXIT_INTERNAL
        }
        $headers = @(Get-ChildItem -LiteralPath $IncludeDir -Recurse -File -Filter *.hpp | ForEach-Object { $_.FullName })
        if ($headers.Count -eq 0) {
            Write-LintLine ('  [lint-doors] no headers under ' + $IncludeDir)
            return $EXIT_INTERNAL
        }
        $virtualsAll = Get-VirtualNames -HeaderPaths $headers
        # The Platform exemption, gated below by Test-NoPlatformInstallPoint.
        $virtuals = Remove-PlatformOnlyNames -Names $virtualsAll
        $exempted = $virtualsAll.Count - $virtuals.Count
        $matcher  = New-DoorMatcher -VirtualNames $virtuals

        # -- the allowlist --------------------------------------------------
        $allow = Read-DoorAllowlist -DocPath $DocPath
        if ($allow.Error) {
            Write-LintLine ('  [lint-doors] ' + $allow.Error)
            return $EXIT_INTERNAL
        }

        # -- the candidate set ----------------------------------------------
        $candidates = New-Object System.Collections.ArrayList
        $guarded    = 0
        $scanned    = 0
        $broken     = New-Object System.Collections.ArrayList

        foreach ($dir in $SrcDirs) {
            if (-not (Test-Path -LiteralPath $dir)) { continue }
            foreach ($f in (Get-ChildItem -LiteralPath $dir -Recurse -File -Include *.cpp | Sort-Object FullName)) {
                $scanned++
                $clean = Get-CleanText $f.FullName
                $idx   = New-LineIndex $clean
                $leaf  = $f.Name

                foreach ($fn in (Split-CppFunctions -Clean $clean)) {
                    if ($fn.Unbalanced) {
                        [void] $broken.Add(($leaf + ' :: ' + $fn.Name))
                        continue
                    }
                    $body = $clean.Substring($fn.BodyStart, $fn.BodyEnd - $fn.BodyStart)
                    $doors = @(Find-Doors -Body $body -Matcher $matcher)
                    if ($doors.Count -eq 0) { continue }

                    $live = @($doors | Where-Object { Test-CodeFollowsDoor -Body $body -DoorOffset $_.Offset })
                    if ($live.Count -eq 0) { continue }

                    if ($body -match $script:CursorGuardPattern) { $guarded++; continue }

                    # NOT $home: that is a read-only automatic variable in
                    # PowerShell and assigning it throws, which this script then
                    # catches and turns into exit 3 -- a red gate for a reason
                    # that has nothing to do with doors.
                    $key = $leaf + '|' + $fn.Name
                    $homeRow = $null
                    if ($allow.Keys.ContainsKey($key)) { $homeRow = $allow.Keys[$key] }

                    $first = $live[0]
                    [void] $candidates.Add(@{
                        File = $leaf
                        Func = $fn.Name
                        Qualified = $fn.Qualified
                        Line = (Get-LineOf -LineStarts $idx -Offset ($fn.BodyStart + $first.Offset))
                        Kinds = (($live | ForEach-Object { $_.Kind }) | Sort-Object -Unique) -join '/'
                        Doors = $live.Count
                        Sample = ($first.Kind + ' ' + $first.Name)
                        Home = $homeRow
                    })
                }
            }
        }

        $unarchived = @($candidates | Where-Object { $null -eq $_.Home })
        $archived   = @($candidates | Where-Object { $null -ne $_.Home })

        # -- the two named machine predicates ---------------------------------
        $platformHits = @(Test-NoPlatformInstallPoint -Root $RepoRoot)
        $batBad       = @(Test-BatchFileHygiene -Root $RepoRoot)

        # -- report -----------------------------------------------------------
        Write-LintLine ('  [lint-doors] {0} virtual name(s) from {1} header(s) ({2} Platform-only, exempt); {3} source file(s); section 11.4 archived {4} row(s)' -f `
            $virtuals.Count, $headers.Count, $exempted, $scanned, $allow.Rows)
        Write-LintLine ('  [lint-doors] candidates: {0} guarded (DeathWatch), {1} archived, {2} UNARCHIVED' -f `
            $guarded, $archived.Count, $unarchived.Count)

        $red = $false

        if ($broken.Count -gt 0) {
            $red = $true
            Write-LintLine '  [lint-doors] FAIL: function bodies this script could not delimit (fail closed):'
            foreach ($b in $broken) { Write-LintLine ('      ' + $b) }
        }

        if ($unarchived.Count -gt 0) {
            $red = $true
            Write-LintLine '  [lint-doors] FAIL: candidates with no home. Guard the frame, or register it'
            Write-LintLine '               in section 11.4 with a reason, a grade and a round:'
            $shown = 0
            foreach ($u in ($unarchived | Sort-Object File, Func)) {
                $shown++
                if ($shown -gt $MaxList) { continue }
                Write-LintLine ('      {0}::{1}  line {2}  [{3}, {4} door(s), first: {5}]' -f `
                    $u.File, $u.Func, $u.Line, $u.Kinds, $u.Doors, $u.Sample)
            }
            if ($unarchived.Count -gt $MaxList) {
                Write-LintLine ('      ... and {0} more.' -f ($unarchived.Count - $MaxList))
            }
        }

        if ($platformHits.Count -gt 0) {
            $red = $true
            Write-LintLine '  [lint-doors] FAIL: an implementation install point for Platform now exists, so'
            Write-LintLine '               section 11.4 s exemption for Platform.hpp s 21 virtuals has lapsed.'
            Write-LintLine '               Put them in the table, graded one by one:'
            foreach ($h in $platformHits) { Write-LintLine ('      ' + $h) }
        }

        if ($batBad.Count -gt 0) {
            $red = $true
            Write-LintLine '  [lint-doors] FAIL: a batch file is no longer pure ASCII. cmd.exe mis-executes a'
            Write-LintLine '               batch file that has BOTH bare-LF endings AND multi-byte characters,'
            Write-LintLine '               and every .bat here is bare-LF, so ASCII is what keeps them working.'
            Write-LintLine '               Move the text into a .ps1, as tools\test-classify-asan.ps1 does:'
            foreach ($b in $batBad) {
                Write-LintLine ('      {0}: {1} non-ASCII byte(s), {2} bare-LF line(s)' -f $b.Name, $b.NonAscii, $b.BareLf)
            }
        }

        if (-not $Quiet -and $archived.Count -gt 0) {
            Write-LintLine '  [lint-doors] archived candidates (section 11.4 has a row for each):'
            foreach ($a in ($archived | Sort-Object File, Func)) {
                Write-LintLine ('      {0}::{1}  line {2}  [{3}]  -> row {4}, {5}, {6}' -f `
                    $a.File, $a.Func, $a.Line, $a.Kinds, $a.Home.Row, $a.Home.Grade, $a.Home.Round)
            }
        }

        if ($red) { return $EXIT_UNCOVERED }
        return $EXIT_COVERED
    }
    catch {
        Write-LintLine ('  [lint-doors] INTERNAL ERROR, failing closed: ' + $_.Exception.Message)
        Write-LintLine ('  [lint-doors] at: ' + $_.InvocationInfo.PositionMessage)
        return $EXIT_INTERNAL
    }
}

# ---------------------------------------------------------------------------
# Script body.  The only `exit` in the file.
# ---------------------------------------------------------------------------
if ($DefineOnly) { return }

exit (Invoke-LintDoorCoverage -RepoRoot $RepoRoot -DocPath $DocPath -MaxList $MaxList -Quiet:$Quiet)

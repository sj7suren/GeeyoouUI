<#
    lint-door-coverage.ps1 -- section 11.9's machine check for DOOR COVERAGE.

    Called by verify.bat, inside step [1/6], before the Release build.  Exit code
    IS the verdict:

        0  every candidate the predicate generated has a home
        1  at least one candidate is neither guarded nor archived  -> gate RED
        3  this script could not parse something, or threw          -> gate RED

    verify.bat treats anything that is not 0 as red.  Same contract as
    tools\classify-asan.ps1, and for the same reason: a checker that fails open
    is worse than no checker, because it looks like one.

    ----------------------------------------------------------------------------
    WHY THIS EXISTS
    ----------------------------------------------------------------------------
    Six recurrences of the same defect family, and every one of them was found by
    a person re-reading code that a person had already reviewed.  E19 wrote the
    sentence this file is the answer to:

        layoutRect() was found by a HUMAN, not by a machine -- which is exactly
        why that lint has to exist, and evidence that it does not yet.

    Section 11.2's static_assert checks a TYPE SHAPE.  deathWatchDepth() checks
    that a list balances.  Neither of them, nor anything else in this tree, can
    say "the ninth door was written without a guard".  That is what is here.

    ----------------------------------------------------------------------------
    THE FOUR PROPERTIES (section 11.9; NOT negotiable, do not relax)
    ----------------------------------------------------------------------------
    1. THE CANDIDATE SET IS GENERATED BY A PREDICATE, not by a list of names
       somebody typed.  Below: split each translation unit into function bodies,
       find the door primitives in each, and emit a candidate for every body that
       has a door which is not its last statement and has no DeathWatch in it.
       Over-reporting is allowed and expected; under-reporting is the defect
       family itself.

    2. EVERY CANDIDATE MUST HAVE A HOME: guarded, or present in the allowlist
       WITH a reason, a grade (S1/S2/S3) and a round (W1/W2/W3).

    3. AN UNARCHIVED CANDIDATE MAKES verify.bat RED.  That is the detection point
       for "the ninth door was written and nobody noticed".

    4. THE P1 HALF OF THE CANDIDATE SET IS GENERATED FROM THE DECLARATION SIDE.
       This one is load bearing and it is the reason the first cut of this scan
       (a grep for a hand-written list of call-site names) missed layoutRect()
       for two rounds: A VIRTUAL CALL HAS NO NAME TO GREP.  Whether `c->foo()`
       is a door depends on whether `foo` is declared virtual in a HEADER, not
       on anything visible at the call site.  So: collect every virtual member
       function name from include\geeyoou\**\*.hpp, and use THAT generated list.

       AND THE SCAN ROOT IS THE WHOLE OF include\geeyoou, not Widget.hpp.  That
       is a SECOND hole, not the same one: Layout::onInvalidated /
       onChildAppended / onChildRemoved were missed because the SUBJECT was
       written too narrowly ("any virtual of a widget"), and declaration-side
       generation rooted at Widget.hpp would still miss all three.  Two holes,
       two fixes, and closing one does not close the other.

       AND THAT ROOT IS THE CANDIDATE SIDE'S TOO -- the same hole, a THIRD time,
       and it stood for three rounds after the other two were closed.  The two
       fixes above were both applied on the DECLARATION side; the CANDIDATE side
       kept scanning `src\**\*.cpp`, and this library's code is not all in src.
       A template in a header is a function body like any other, and two of them
       were doors with writes after them: AppWindow::setContent and
       WindowHeader::addTrailingItem.  Whoever narrows a scan root next: the
       question is never "where are the .cpp files", it is "where is the code".

       (Two mechanical traps came with it, both measured, both recorded at their
       fix: -Include does nothing next to -LiteralPath -Recurse, and `template`
       is in NotAFunctionHead so every template body read as "not a function".
       Widening the root without the second fix buys exactly nothing.)

    ----------------------------------------------------------------------------
    THE ALLOWLIST AND THE P2 LIST ARE SECTION 11.4'S.  THERE IS NO SECOND COPY.
    ----------------------------------------------------------------------------
    This script parses docs\iterations\02-layout-engine.md section 11.4 and takes
    its tables as the register of archived candidates, AND its P2 clause as the
    list of library primitives that reach application code.  Writing either out a
    second time here would be the mistake Widget.cpp:74-75 already names: the
    second hand-copy is the second place that gets forgotten -- and the P2 copy
    HAD already drifted (the script had `relayout`, the document did not) with a
    comment above it saying "when you add one here, add it there too".

    THE KEY IS (FILE, FUNCTION), NOT (FILE, LINE).  The table's own words:
    "the statement is what the table is about, the line number is not" -- line
    numbers in that table were already stale by a hundred lines after E14, and a
    lint keyed on them would redden on every unrelated edit, which is the
    always-on red light section 11.9 rejected the runtime counter for being.

    ----------------------------------------------------------------------------
    FAIL-CLOSED, EVERYWHERE
    ----------------------------------------------------------------------------
      * a function body this script cannot delimit        -> reported, red
      * a table row with no grade or no round             -> NOT archived
      * a table row naming a file but no function         -> NOT archived
      * a doc with no parseable section 11.4              -> exit 3, red
      * a source file that cannot be read                 -> exit 3, red

    A false red costs somebody an hour.  A false green costs a use-after-free in
    a release, and all six in this family were green on two of the three legs.

    ----------------------------------------------------------------------------
    WHAT THIS DELIBERATELY DOES NOT DO
    ----------------------------------------------------------------------------
      * It does not decide DANGER.  Section 11.4's hazard clause ("the door is
        dangerous to P iff something after it reaches through P") needs to know
        what a name refers to, which needs a compiler.  This script answers the
        cheaper question -- is there a door with code after it and no cursor --
        and makes a HUMAN answer the expensive one, in the table, on the record.
      * It does not tell HOLDING a cursor from CHECKING one.  Section 11.9 says
        "no DeathWatch in the body"; this file reads that as "no REM3 cursor in
        the body", because all four of them (DeathWatch, BubbleGuard,
        GeometryGuard, LayoutGuard) are the same LiveGuard mechanism and the
        literal reading filed Widget::dispatchMouse and dispatchKey as defects
        while both of them re-test their cursor after the door.  The widening is
        argued where it is implemented ($CursorGuardPattern) and the residue it
        leaves is registered in section 12.4 rather than glossed over.
      * It does not scan tests\ or examples\.  Section 11.4 row #25 registers the
        examples exposure separately and R3 does not change examples.
#>


# The door primitives, section 11.4.
#
# P2's list is the one in the document, verbatim, INCLUDING the transitivity
# clause: a library function found to contain a door gets added to this list and
# the scan is re-run.  When you add one here, add it there too -- the list in
# the document is the one a human reads.
# ---------------------------------------------------------------------------
$script:P2Names = @(
    'setGeometry', 'setVisible', 'setLayout', 'invalidateSizeHint', 'add',
    'takeChild', 'removeChild', 'clearChildren', 'openPopup', 'closePopup',
    'performLayout', 'arrange', 'measure', 'measureFor', 'relayout'
)

# ONE compiled alternation per primitive class, not one regex per name.
#
# Not a micro-optimisation: with 38 virtual names and 15 P2 names, per-name
# scanning is 53 passes over every function body in the tree, and it measured
# 14.9 SECONDS on this repository.  The gate runs this, and the self-test runs
# it twice more; a check that adds three quarters of a minute to every build is
# a check somebody deletes.  Folded into three passes it is under a second.
#
# `(?<!::)` rather than capturing the two preceding characters: a QUALIFIED call
# is statically bound and is not a P1 door (section 11.4), and a lookbehind
# expresses that without consuming input -- which matters, because a consuming
# prefix makes two adjacent calls overlap and silently drops the second.  A
# dropped door is an under-report, and under-reporting is the defect family.
function New-DoorMatcher {
    param([hashtable] $VirtualNames)

    $opt = [System.Text.RegularExpressions.RegexOptions]::Compiled
    # `(?!)` is the never-matching pattern.  It is here because the alternative
    # is far worse than it looks: an EMPTY name list builds `(?<n>)`, an empty
    # alternation, and `(?<!::)\b(?<n>)\s*\(` then matches EVERY parenthesis in
    # the tree with an empty door name.  Caught by the Platform-exemption
    # fixture, where the exemption legitimately empties the P1 set, and it
    # produced `first: P1 ` with nothing after it -- output that is not merely
    # over-red but meaningless, which is how a gate stops being read.
    $never = '(?!)'

    $p1 = $never
    if ($VirtualNames.Count -gt 0) {
        $p1 = '(?<!::)\b(?<n>' +
              (($VirtualNames.Keys | Sort-Object | ForEach-Object { [regex]::Escape($_) }) -join '|') +
              ')\s*\('
    }
    $p2 = $never
    if ($script:P2Names.Count -gt 0) {
        $p2 = '(?<!::)\b(?<n>' +
              (($script:P2Names | Sort-Object | ForEach-Object { [regex]::Escape($_) }) -join '|') +
              ')\s*[<(]'
    }

    return @{
        P1 = New-Object System.Text.RegularExpressions.Regex($p1, $opt)
        P2 = New-Object System.Text.RegularExpressions.Regex($p2, $opt)
        P3 = New-Object System.Text.RegularExpressions.Regex('(\.|->)emit\s*\(', $opt)
    }
}

function Find-Doors {
    param([string] $Body, [hashtable] $Matcher)

    $doors = New-Object System.Collections.ArrayList

    # P1 -- generated from the declaration side.  `x->foo()`, `x.foo()` and a
    # bare `foo()` are all dispatch; `Base::foo()` is not.
    foreach ($m in $Matcher.P1.Matches($Body)) {
        [void] $doors.Add(@{ Kind = 'P1'; Name = $m.Groups['n'].Value; Offset = $m.Index })
    }
    # P2 -- named library functions known to reach application code.
    foreach ($m in $Matcher.P2.Matches($Body)) {
        [void] $doors.Add(@{ Kind = 'P2'; Name = $m.Groups['n'].Value; Offset = $m.Index })
    }
    # P3 -- signal emission.
    foreach ($m in $Matcher.P3.Matches($Body)) {
        [void] $doors.Add(@{ Kind = 'P3'; Name = 'emit'; Offset = $m.Index })
    }

    return ($doors | Sort-Object { $_.Offset })
}

# ---------------------------------------------------------------------------
# WHAT COUNTS AS A CURSOR ON THIS FRAME.
#
# Section 11.9 says "no DeathWatch in the body", and the first cut of this file
# took that literally because the literal reading is the redder one.  It was
# WRONG, and measurably so, not as a matter of taste: it reported
# Widget::dispatchMouse and Widget::dispatchKey as unguarded, and both of them
# carry a BubbleGuard AND re-test it after the door --
#
#     w->onMouse(local);              <- the door
#     if (local.accepted) { ... }
#     if (bubble.node() != w) return; <- the check
#
# -- which is the very shape REM3-G2/G3 ask for, written before REM3 existed.
# A lint that files a correct frame as a defect is how a lint gets muted, and a
# muted lint is the failure mode section 11.9 rejected the runtime counter for.
#
# So the predicate is "the frame holds a REM3 CURSOR", and all four of them are
# the same mechanism: LiveGuard<List> over a list that ~Widget cancels.
# DeathWatch was simply the only one in scope when 11.9 was written.
#
# ⚠ REGISTERED RESIDUE, because this is a WIDENING and widenings are how this
# family recurs: holding a cursor is not the same as CHECKING it, and this test
# cannot tell the two apart.  A frame that constructs a LayoutGuard for its own
# reasons and then walks through a door without asking alive() reads as guarded
# here.  Closing that needs the check to be tied to the door, which needs to
# know which pointer the door is dangerous to -- section 11.4's hazard clause,
# i.e. a compiler.  Recorded in section 12.4 rather than pretended away.
$script:CursorGuardPattern = '\b(DeathWatch|BubbleGuard|GeometryGuard|LayoutGuard)\b'

# Is there any code after this door's own statement, other than the closing
# brace?  "The door is the last statement" is section 11.9's one exclusion, and
# ScrollArea.cpp:165 / :174 and Widget.cpp:548 are the rows it exists for.
function Test-CodeFollowsDoor {
    param([string] $Body, [int] $DoorOffset)

    $depth = 0
    $i = $DoorOffset
    $n = $Body.Length
    while ($i -lt $n) {
        $c = $Body[$i]
        if ($c -eq '(' -or $c -eq '[' -or $c -eq '{') { $depth++ }
        elseif ($c -eq ')' -or $c -eq ']' -or $c -eq '}') {
            $depth--
            # Ran off the end of the body without a `;`: the door was the last
            # expression, e.g. `return layout_->measureFor(...)` has its `;`
            # first, so this only happens on malformed input.  Fail closed.
            if ($depth -lt 0) { return $true }
        }
        elseif ($c -eq ';' -and $depth -eq 0) { break }
        $i++
    }
    if ($i -ge $n) { return $true }
    $tail = $Body.Substring($i + 1)
    $tail = [regex]::Replace($tail, '[\s}]', '')
    return ($tail.Length -gt 0)
}

# ---------------------------------------------------------------------------
# THE ALLOWLIST: section 11.4 of the design document.  Parsed, never copied.
# ---------------------------------------------------------------------------
function Read-DoorAllowlist {
    param([string] $DocPath)

    $result = @{ Keys = @{}; Rows = 0; Error = '' }

    if (-not (Test-Path -LiteralPath $DocPath)) {
        $result.Error = 'design document not found: ' + $DocPath
        return $result
    }

    $lines = [System.IO.File]::ReadAllLines($DocPath, [System.Text.Encoding]::UTF8)

    $inSection = $false
    foreach ($line in $lines) {
        if ($line -match '^###\s+11\.4(\s|$)')  { $inSection = $true;  continue }
        if ($inSection -and $line -match '^###\s+11\.5(\s|$)') { $inSection = $false; break }
        if (-not $inSection) { continue }
        if ($line -notmatch '^\s*\|') { continue }

        $cells = $line.Split('|')
        # A markdown row splits to: '', c1, c2, ..., cN, ''
        if ($cells.Count -lt 6) { continue }
        $c = @()
        for ($k = 1; $k -lt $cells.Count - 1; $k++) { $c += $cells[$k].Trim() }
        if ($c.Count -lt 5) { continue }
        # Header and separator rows.
        if ($c[0] -match '^:?-{2,}') { continue }
        if ($c[0] -eq '#') { continue }

        $loc = $c[1]

        # Property 2: a row without BOTH a grade and a round archives nothing.
        # The main table is 8 columns (grade 6, round 7); the N table is 6
        # (grade 5, round 6).  Read them from the END so both shapes work: the
        # main table ends with an action column, the N table does not.
        $grade = ''; $round = ''
        if ($c.Count -ge 8)     { $grade = $c[5]; $round = $c[6] }
        elseif ($c.Count -eq 6) { $grade = $c[4]; $round = $c[5] }
        else                    { continue }
        if (-not $grade -or -not $round) { continue }

        $files = @()
        foreach ($m in [regex]::Matches($loc, '([A-Za-z_]\w*\.(?:cpp|hpp))')) {
            if (-not ($files -contains $m.Groups[1].Value)) { $files += $m.Groups[1].Value }
        }
        if ($files.Count -eq 0) { continue }

        # Function names: every backticked identifier in the location cell that
        # is not the file name itself.  `setContentSize`, `Layout::invalidate()`,
        # `contentRect()` all reduce to a bare name.
        $funcs = @()
        foreach ($m in [regex]::Matches($loc, '`([^`]+)`')) {
            $tok = $m.Groups[1].Value
            foreach ($idm in [regex]::Matches($tok, '(?<n>[A-Za-z_]\w*)\s*(\(\s*\))?\s*$')) {
                $nm = $idm.Groups['n'].Value
                if ($nm -match '\.(cpp|hpp)$') { continue }
                if ($tok -match '\.(cpp|hpp)') { continue }
                if (-not ($funcs -contains $nm)) { $funcs += $nm }
            }
        }
        if ($funcs.Count -eq 0) { continue }

        $result.Rows++
        foreach ($f in $files) {
            foreach ($fn in $funcs) {
                $result.Keys[($f + '|' + $fn)] = @{ Grade = $grade; Round = $round; Row = $c[0] }
            }
        }
    }

    if ($result.Rows -eq 0) { $result.Error = 'no parseable rows in section 11.4 of ' + $DocPath }
    return $result
}

